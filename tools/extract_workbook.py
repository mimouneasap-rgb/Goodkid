"""Extract the raw (non-formula) tables of the El Kendi QA master workbook into oncology/js/workbook-data.js.

Usage: python3 tools/extract_workbook.py ElKendi_Oncology_QA_Master_Workbook.xlsx oncology/js/workbook-data.js

Also writes oncology/js/schema.js (column names + translations only). The data file holds confidential
records and is git-ignored; the app loads it when present, otherwise users import the workbook in the browser.
"""
import openpyxl, json, sys, datetime
from openpyxl.utils import column_index_from_string as ci

src, out = sys.argv[1], sys.argv[2]
wb = openpyxl.load_workbook(src)

def val(v):
    if isinstance(v, datetime.datetime):
        return v.strftime('%Y-%m-%d') if (v.hour, v.minute) == (0, 0) else v.strftime('%Y-%m-%dT%H:%M')
    if isinstance(v, datetime.date):
        return v.isoformat()
    if isinstance(v, datetime.time):
        return None
    if isinstance(v, str):
        v = v.strip()
        if v.startswith('='):
            return None
        return v or None
    return v

def table(sheet, name, keep=None):
    ws = wb[sheet]
    t = ws.tables[name]
    rows = list(ws[t.ref])
    hdr = [c.value for c in rows[0]]
    second = rows[1] if len(rows) > 1 else []
    # drop formula columns: anything whose first data cell is a formula
    cols = [i for i, h in enumerate(hdr)
            if not (second and isinstance(second[i].value, str) and second[i].value.startswith('='))]
    if keep:
        cols = [i for i in cols if hdr[i] in keep]
    data = []
    for r in rows[1:]:
        rec = [val(r[i].value) for i in cols]
        if any(x is not None for x in rec):
            data.append(rec)
    return {'cols': [hdr[i] for i in cols], 'rows': data}

def rng(sheet, a, b):
    ws = wb[sheet]
    return [[val(c.value) for c in row] for row in ws[f'{a}:{b}']]

home = wb['Home']
dq = wb['Data Quality']
fm = wb['FMEA Risk']
ws_map = wb['Facility Map']

grid = []
for r in range(5, 74):
    grid.append([ws_map.cell(r, c).value or '' for c in range(ci('BI'), ci('CP') + 1)])

lists = wb['Lists']
settings = {lists.cell(r, ci('BK')).value: lists.cell(r, ci('BL')).value for r in range(2, 11)
            if lists.cell(r, ci('BK')).value}

data = {
    'meta': {
        'asof': val(home['C6'].value),
        'generated': val(home['C7'].value),
        'docControl': [[home.cell(r, 8).value, val(home.cell(r, 9).value)] for r in range(10, 17)],
        'history': [[home.cell(r, 2).value, home.cell(r, 3).value] for r in range(61, 66) if home.cell(r, 2).value],
        'assumptions': [[home.cell(r, 2).value, home.cell(r, 3).value] for r in range(39, 58) if home.cell(r, 2).value],
        'inconsistencies': [[dq.cell(r, 2).value, dq.cell(r, 3).value] for r in range(97, 110) if dq.cell(r, 2).value],
        'reconExpected': {dq.cell(r, 2).value: dq.cell(r, 11).value for r in range(24, 35)},
        'reviewPeriod': wb['Management Review']['D6'].value,
        'annex01': [[fm.cell(r, c).value for c in (2, 5, 6, 7, 8, 9)] for r in range(84, 94) if fm.cell(r, 2).value],
        'settings': {k: v for k, v in settings.items() if not (isinstance(v, str) and v.startswith('='))},
    },
    'rooms': table('Rooms', 'tRooms'),
    'adj': table('Rooms', 'tAdj'),
    'equip': table('Equipment', 'tEquip'),
    'sop': table('SOP Library', 'tSOP'),
    'forms': table('Logbooks & Forms', 'tForms'),
    'ccp': table('CCP', 'tCCP'),
    'fmea': table('FMEA', 'tFMEA'),
    'impr': table('Improvements', 'tImpr'),
    'appr': table('Approvals Log', 'tAppr'),
    'links': table('Record Links', 'tLinks'),
    'cc': table('Import_CC', 'tCC'),
    'capa': table('Import_CAPA', 'tCAPA'),
    'qe': table('Import_QE', 'tQE'),
    'bands': table('Lists', 'tBands'),
    'targets': table('Lists', 'tTargets'),
    'crit': table('Lists', 'tCrit'),
    'deptMap': table('Lists', 'tDeptMap'),
    'prio': table('Lists', 'tPrio'),
    'prod': table('Lists', 'tProd'),
    'tr': table('Lists', 'tTr')['rows'],
    'mapGrid': grid,
}
for k in ('rooms','equip','fmea','cc','capa','qe','sop'):
    print(k, len(data[k]['rows']), data[k]['cols'], file=sys.stderr)
print(json.dumps(data['meta']['settings'], ensure_ascii=False), file=sys.stderr)
data['meta']['drawing'] = 'assets/layout-elk-dwg-048.jpg'  # local copy, git-ignored like the data file

# Non-confidential schema (column names + UI translations), committed with the app.
schema = {'cols': {k: v['cols'] for k, v in data.items() if isinstance(v, dict) and 'cols' in v}, 'tr': data['tr']}
schema_path = out.replace('workbook-data.js', 'schema.js')
with open(schema_path, 'w', encoding='utf-8') as f:
    f.write('// Column layout of the master workbook tables and the UI translation table (Lists → tTr).\n')
    f.write('// Generated by tools/extract_workbook.py. Holds no records.\n')
    f.write('export default ')
    json.dump(schema, f, ensure_ascii=False, indent=0)
    f.write(';\n')

with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated from ElKendi_Oncology_QA_Master_Workbook.xlsx by tools/extract_workbook.py – do not edit by hand.\n')
    f.write('export default ')
    json.dump(data, f, ensure_ascii=False, separators=(',', ':'))
    f.write(';\n')
